const myKeyUp = (e) => {
  let list = bottomList.value;
  let currentRow = e
  let oldCurrentRow = tempCurrentRow.value
  if (currentRow.groupId === '2') {//小计
    getXj(list, currentRow, oldCurrentRow, true);
  } else if (currentRow.groupId === '3') {//合计
    let currentHjRowKey = currentRow.groupKey
    let hJTon = currentRow.ton
    let oldHjTon = oldCurrentRow.ton ? oldCurrentRow.ton : 0;
    let xjCount = 0;
    for (let index in list) {
      let item = list[index]
      //检索小计
      if (item.groupKey && item.groupId == '2') {
        let keys = item.groupKey.split("_");
        let itemKey = keys[0] + "_" + keys[1];
        if (itemKey == currentHjRowKey) {
          xjCount++;
          if (oldHjTon != 0) {
            let xjTon = item.ton
            let oldXj = {ton: item.ton}
            item.ton = hJTon ? (xjTon == oldHjTon ? hJTon : Math.round((hJTon * (xjTon / oldHjTon))*100)/100) : 0;
            getXj(list, item, oldXj, false);
          }
        }
      }
    }
    for (let index in list) {
      let item = list[index]
      //检索小计
      if (oldHjTon == 0) {
        if (item.groupKey && item.groupId == '2') {
          let keys = item.groupKey.split("_");
          let itemKey = keys[0] + "_" + keys[1];
          if (itemKey == currentHjRowKey) {
            if (oldHjTon == 0) {
              let xjTon = item.ton
              let oldXj = {ton: 0}
              item.ton = hJTon ? Math.round(100*(hJTon / xjCount))/100  : 0;
              getXj(list, item, oldXj, false);
            }
          }
        }
      }
    }
  } else {
    if (oldCurrentRow != null && currentRow != null) {
      let currentXjRowKey = currentRow.processDetailCode + "_" + currentRow.workPositionCode + "_" + currentRow.deptId + (currentRow.equipmentTypeName ? ("_" + currentRow.equipmentTypeName) : '')
      let currentHjRowKey = currentRow.processDetailCode + "_" + currentRow.workPositionCode
      let xjTon = 0
      let hJTon = 0
      let xjIndex = null;
      let hjIndex = null;
      for (let index in list) {
        let item = list[index]
        let itemXjKey = item.processDetailCode + "_" + item.workPositionCode + "_" + item.deptId + (item.equipmentTypeName ? ("_" + item.equipmentTypeName) : '')
        let itemHjKey = item.processDetailCode + "_" + item.workPositionCode
        if (itemXjKey == currentXjRowKey && item.groupId != '2' && item.groupId != '3') {
          xjTon = math.numAdd(Number(item.ton), Number(xjTon))
        }
        if (itemHjKey == currentHjRowKey && item.groupId != '2' && item.groupId != '3') {
          hJTon = math.numAdd(Number(item.ton), Number(hJTon))
        }
        // 10250003_01_01_挖掘机
        if (item.groupKey == currentXjRowKey && item.groupId == '2') {
          xjIndex = index;
        }
        if (item.groupKey == currentHjRowKey && item.groupId == '3') {
          hjIndex = index;
        }
      }
      list[xjIndex].ton = xjTon;
      list[hjIndex].ton = hJTon;
      changeXjHuiZong(list[xjIndex].groupKey,list[xjIndex].ton)
      // changeHjHuiZong(list[hjIndex].groupKey,list[hjIndex].ton)
    }
  }
}

const getXj = (list, currentRow, oldCurrentRow, flag) => {
  let oldTon = oldCurrentRow.ton ? oldCurrentRow.ton : 0;
  let xjTon = currentRow.ton
  let hJTon = 0
  let hjIndex = null;
  let currentXjRowKey = currentRow.groupKey
  let keys = currentRow.groupKey.split('_')
  let currentHjRowKey = keys[0] + "_" + keys[1];
  let mxCount = 0;
  if (oldTon != 0) {
    for (let index in list) {
      let item = list[index]
      let itemKey = item.processDetailCode + "_" + item.workPositionCode + "_" + item.deptId + (item.equipmentTypeName ? ("_" + item.equipmentTypeName) : '')
      let itemHjKey = item.processDetailCode + "_" + item.workPositionCode
      if (currentXjRowKey == itemKey && item.groupId != '2' && item.groupId != '3') {
        item.ton = xjTon ? item.ton == oldTon ? xjTon : Math.round(xjTon * (item.ton / oldTon)*100)/100 : 0
      }
      if (itemHjKey == currentHjRowKey && item.groupId != '2' && item.groupId != '3') {
        hJTon = math.numAdd(Number(item.ton), Number(hJTon))
      }
      if (item.groupKey == currentHjRowKey && item.groupId == '3') {
        hjIndex = index;
      }
    }
  }
  if (oldTon == 0) {
    for (let index in list) {
      let item = list[index]
      let itemKey = item.processDetailCode + "_" + item.workPositionCode + "_" + item.deptId + (item.equipmentTypeName ? ("_" + item.equipmentTypeName) : '')
      if (currentXjRowKey == itemKey && item.groupId != '2' && item.groupId != '3') {
        mxCount++
      }
    }
    for (let index in list) {
      let item = list[index]
      let itemKey = item.processDetailCode + "_" + item.workPositionCode + "_" + item.deptId + (item.equipmentTypeName ? ("_" + item.equipmentTypeName) : '')
      let itemHjKey = item.processDetailCode + "_" + item.workPositionCode
      if (currentXjRowKey == itemKey && item.groupId != '2' && item.groupId != '3') {
        item.ton = Math.round((xjTon / mxCount)*100)/100
      }
      if (itemHjKey == currentHjRowKey && item.groupId != '2' && item.groupId != '3') {
        hJTon = math.numAdd(Number(item.ton), Number(hJTon))
      }
      if (item.groupKey == currentHjRowKey && item.groupId == '3') {
        hjIndex = index;
      }
    }
  }
  if (flag) {
    list[hjIndex].ton = Math.round(hJTon*100)/100;
  }
  changeXjHuiZong(currentXjRowKey,xjTon)
  // changeHjHuiZong(currentHjRowKey,hJTon)
}

