const topSpanMethod = ({row, column, rowIndex, columnIndex}) => {
  let list = topCollect.value
  // 自定义合并规则
  if (columnIndex === 0) {
    // 第一列合并逻辑示例
    // 判断当前行和上一行的数据是否相同，相同则合并
    if (rowIndex > 0 && list[rowIndex - 1].processDetailName === row.processDetailName) {
      return {
        rowspan: 0,
        colspan: 0,
      }
    }
    // 计算合并的行数
    let rowspan = 1
    for (let i = rowIndex + 1; i < list.length; i++) {
      if (list[i].processDetailName == row.processDetailName) {
        rowspan++
      } else {
        break
      }
    }
    return {
      rowspan: rowspan,
      colspan: 1,
    }
  }
  if ((columnIndex === 4 && allotType.value==3) || (columnIndex === 6 && allotType.value==2) || (columnIndex === 1 && allotType.value==2) || (columnIndex === 1 && allotType.value==3)) {
    // 第一列合并逻辑示例
    // 判断当前行和上一行的数据是否相同，相同则合并
    if (rowIndex > 0 && list[rowIndex - 1].workPositionName === row.workPositionName && list[rowIndex - 1].processDetailName === row.processDetailName) {
      return {
        rowspan: 0,
        colspan: 0,
      }
    }
    // 计算合并的行数
    let rowspan = 1
    for (let i = rowIndex + 1; i < list.length; i++) {
      if (list[i].workPositionName == row.workPositionName  && list[i].processDetailName === row.processDetailName) {
        rowspan++
      } else {
        break
      }
    }
    return {
      rowspan: rowspan,
      colspan: 1,
    }
  }
}
